mod tests {
    use super::*;

    #[test]
    fn lookup_tables_are_ordered_and_cover_the_disc_voices() {
        let voices: &[(u16, &[(u16, u16)])] = &[
            (1, &VOICE_1),
            (2, &VOICE_2),
            (3, &VOICE_3),
            (4, &VOICE_4),
            (5, &VOICE_5),
            (6, &VOICE_6),
            (7, &VOICE_7),
            (8, &VOICE_8),
            (9, &VOICE_9),
            (10, &VOICE_10),
            (11, &VOICE_11),
            (12, &VOICE_12),
            (13, &VOICE_13),
            (14, &VOICE_14),
            (15, &VOICE_15),
            (16, &VOICE_16),
            (145, &VOICE_145),
            (146, &VOICE_146),
            (147, &VOICE_147),
            (148, &VOICE_148),
            (149, &VOICE_149),
            (151, &VOICE_151),
        ];

        let mut count = 0;
        for &(voice, entries) in voices {
            assert!(entries.windows(2).all(|w| w[0].0 < w[1].0), "voice {voice}");
            for &(start, stream) in entries {
                assert_eq!(
                    lookup(voice, start),
                    Some(stream),
                    "voice {voice}, {start:#x}"
                );
                count += 1;
            }
        }
        assert_eq!(count, 3196);
    }

    #[test]
    fn unknown_voices_and_header_starts_do_not_resolve() {
        assert_eq!(lookup(0, 0), None);
        assert_eq!(lookup(17, 0), None);
        assert_eq!(lookup(150, 0), None);
        assert_eq!(lookup(1, u16::MAX), None);
        assert_eq!(lookup(151, 1), None);
    }
}
